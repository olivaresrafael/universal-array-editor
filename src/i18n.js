let language = 'en';
try {
  language = localStorage.getItem('array-editor-language') === 'es' ? 'es' : 'en';
} catch { /* Storage may be disabled by browser privacy settings. */ }

export function getLanguage() {
  return language;
}

export function setLanguage(next) {
  language = next === 'es' ? 'es' : 'en';
  try {
    localStorage.setItem('array-editor-language', language);
  } catch { /* Private browsing may block storage. */ }
}

export function tr(key, values = {}) {
  const template = translations[language][key] ?? translations.en[key] ?? key;
  return String(template).replace(/\{(\w+)\}/g, (_, name) => String(values[name] ?? `{${name}}`));
}
